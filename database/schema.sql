-- Finance Management System: wstępny schemat PostgreSQL (wersja robocza)
-- Cel: PostgreSQL 16 (zgodnie z docker-compose.yml)
-- Typy enum to wersje snake_case enumów z DBML (Role -> user_role itd.).
-- Klucze główne używają kolumn identity; DBML nie określa sposobu generowania id.

BEGIN;

-- Enums
CREATE TYPE category_type AS ENUM ('Expense', 'Income', 'Transfer');
CREATE TYPE user_status AS ENUM ('PendingVerification', 'Active', 'Suspended', 'Deactivated');
CREATE TYPE user_role AS ENUM ('User', 'Admin', 'Manager');
CREATE TYPE household_role AS ENUM ('Owner', 'Member', 'Viewer');
CREATE TYPE receipt_status AS ENUM ('Uploaded', 'Processed', 'Failed');
CREATE TYPE invitation_status AS ENUM ('Pending', 'Accepted', 'Declined', 'Expired');

-- Gospodarstwa domowe (bez zależności FK; tworzone jako pierwsze, bo users się do nich odwołują)
CREATE TABLE households (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL,
    currency varchar(3) NOT NULL DEFAULT 'PLN',
    is_personal boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

-- Użytkownicy
CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name varchar(100),
    last_name varchar(100),
    email varchar(255) NOT NULL UNIQUE,
    role user_role NOT NULL DEFAULT 'User',
    status user_status NOT NULL DEFAULT 'PendingVerification',
    password_hash varchar(255) NOT NULL,
    password_reset_token varchar(255),
    password_reset_expires_at timestamptz,
    email_verified_at timestamptz,
    failed_login_attempts integer NOT NULL DEFAULT 0,
    locked_until timestamptz,
    personal_household_id bigint UNIQUE REFERENCES households (id),
    email_verification_token varchar(255),
    email_verification_expires_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz
);
CREATE INDEX users_deleted_at_idx ON users (deleted_at);

CREATE TABLE user_profiles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL UNIQUE REFERENCES users (id),
    phone_number varchar(18),
    date_of_birth date,
    preferred_language varchar(10) DEFAULT 'pl',
    preferred_chart varchar(20) NOT NULL DEFAULT 'pie',
    consent_personal_data boolean NOT NULL DEFAULT false,
    consent_marketing boolean NOT NULL DEFAULT false,
    consent_updated_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX user_profiles_phone_number_key ON user_profiles (phone_number);

-- Członkowie gospodarstw i zaproszenia
CREATE TABLE household_members (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id bigint NOT NULL REFERENCES households (id),
    user_id bigint NOT NULL REFERENCES users (id),
    role household_role NOT NULL DEFAULT 'Member',
    joined_at timestamptz NOT NULL DEFAULT now(),
    left_at timestamptz,
    UNIQUE (household_id, user_id)
);
CREATE INDEX household_members_user_id_idx ON household_members (user_id);

CREATE TABLE household_invitations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id bigint NOT NULL REFERENCES households (id),
    email varchar(255) NOT NULL,
    invited_by bigint NOT NULL REFERENCES users (id),
    accepted_by bigint REFERENCES users (id),
    token varchar(255) NOT NULL UNIQUE,
    status invitation_status NOT NULL DEFAULT 'Pending',
    expires_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX household_invitations_household_email_idx ON household_invitations (household_id, email);

-- Kategorie (parent_id odwołuje się do tej samej tabeli)
CREATE TABLE categories (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint REFERENCES users (id),
    household_id bigint REFERENCES households (id),
    name varchar(100) NOT NULL,
    slug varchar(120) NOT NULL,
    icon varchar(50),
    color varchar(7),
    type category_type NOT NULL DEFAULT 'Expense',
    parent_id integer REFERENCES categories (id),
    is_system boolean NOT NULL DEFAULT false,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX categories_user_id_idx ON categories (user_id);
CREATE INDEX categories_household_id_idx ON categories (household_id);
CREATE INDEX categories_parent_id_idx ON categories (parent_id);
CREATE UNIQUE INDEX categories_user_id_slug_key ON categories (user_id, slug);
CREATE UNIQUE INDEX categories_household_id_slug_key ON categories (household_id, slug);

CREATE TABLE category_limits (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users (id),
    household_id bigint NOT NULL REFERENCES households (id),
    category_id integer NOT NULL REFERENCES categories (id),
    limit_amount decimal(12, 2) NOT NULL,
    month_year varchar(7) NOT NULL,
    threshold_percentage smallint NOT NULL DEFAULT 80,
    currency varchar(3) NOT NULL DEFAULT 'PLN',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (household_id, category_id, month_year)
);

-- Kursy walut
CREATE TABLE exchange_rates (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    currency_code varchar(3) NOT NULL,
    rate decimal(12, 6) NOT NULL,
    effective_date date NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (currency_code, effective_date)
);

-- Subskrypcje cykliczne (muszą istnieć przed transactions, które się do nich odwołują)
CREATE TABLE recurring_subscriptions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id bigint NOT NULL REFERENCES households (id),
    user_id bigint NOT NULL REFERENCES users (id),
    category_id integer NOT NULL REFERENCES categories (id),
    title varchar(150) NOT NULL,
    amount decimal(12, 2) NOT NULL,
    currency varchar(3) NOT NULL DEFAULT 'PLN',
    billing_day smallint NOT NULL,
    next_billing_date date NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX recurring_subscriptions_household_id_idx ON recurring_subscriptions (household_id);
CREATE INDEX recurring_subscriptions_user_id_idx ON recurring_subscriptions (user_id);
CREATE INDEX recurring_subscriptions_next_billing_date_idx ON recurring_subscriptions (next_billing_date);

-- Paragony (muszą istnieć przed transactions, które się do nich odwołują)
CREATE TABLE receipts (
    id BIGSERIAL PRIMARY KEY,
    household_id BIGINT NOT NULL REFERENCES households(id) ON DELETE CASCADE,
    payer_id BIGINT NOT NULL REFERENCES users(id),
    created_by BIGINT NOT NULL REFERENCES users(id),
    status receipt_status NOT NULL DEFAULT 'Uploaded',
    merchant VARCHAR(150),
    receipt_date DATE,
    total_amount DECIMAL(12, 2),
    currency VARCHAR(3) NOT NULL DEFAULT 'PLN',
    raw_text JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_receipts_household_id ON receipts(household_id);
CREATE INDEX idx_receipts_payer_id ON receipts(payer_id);

-- Transakcje
CREATE TABLE transactions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id bigint NOT NULL REFERENCES households (id),
    user_id bigint NOT NULL REFERENCES users (id),
    category_id integer NOT NULL REFERENCES categories (id),
    amount decimal(12, 2) NOT NULL,
    currency varchar(3) NOT NULL DEFAULT 'PLN',
    type category_type NOT NULL,
    base_amount decimal(12, 2) NOT NULL,
    base_currency varchar(3) NOT NULL DEFAULT 'PLN',
    exchange_rate decimal(12, 6) NOT NULL DEFAULT 1,
    rate_date date,
    transaction_date date NOT NULL,
    description varchar(255),
    receipt_id bigint REFERENCES receipts (id),
    recurring_subscription_id bigint REFERENCES recurring_subscriptions (id),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz
);
CREATE INDEX transactions_user_id_idx ON transactions (user_id);
CREATE INDEX transactions_category_id_idx ON transactions (category_id);
CREATE INDEX transactions_household_id_idx ON transactions (household_id);
CREATE INDEX transactions_receipt_id_idx ON transactions (receipt_id);
CREATE INDEX transactions_recurring_subscription_id_idx ON transactions (recurring_subscription_id);
CREATE INDEX transactions_user_date_idx ON transactions (user_id, transaction_date);
CREATE INDEX transactions_user_type_date_idx ON transactions (user_id, type, transaction_date);
CREATE INDEX transactions_household_date_idx ON transactions (household_id, transaction_date);

CREATE TABLE transaction_splits (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id bigint NOT NULL REFERENCES transactions (id),
    user_id bigint NOT NULL REFERENCES users (id),
    percentage decimal(5, 2) NOT NULL,
    share_amount decimal(12, 2) NOT NULL,
    UNIQUE (transaction_id, user_id)
);

-- Pozycje paragonów (transaction_id jest nullable i unikalne: najwyżej jedna transakcja na pozycję)
CREATE TABLE receipt_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_id bigint NOT NULL REFERENCES receipts (id),
    transaction_id bigint UNIQUE REFERENCES transactions (id),
    name varchar(255) NOT NULL,
    amount decimal(12, 2) NOT NULL,
    category_id integer REFERENCES categories (id),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX receipt_items_receipt_id_idx ON receipt_items (receipt_id);
CREATE INDEX receipt_items_category_id_idx ON receipt_items (category_id);

-- Rozliczenia
CREATE TABLE settlements (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id bigint NOT NULL REFERENCES households (id),
    payer_id bigint NOT NULL REFERENCES users (id),
    receiver_id bigint NOT NULL REFERENCES users (id),
    amount decimal(12, 2) NOT NULL,
    currency varchar(3) NOT NULL DEFAULT 'PLN',
    settled_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX settlements_household_id_idx ON settlements (household_id);
CREATE INDEX settlements_payer_id_idx ON settlements (payer_id);
CREATE INDEX settlements_receiver_id_idx ON settlements (receiver_id);

COMMIT;
