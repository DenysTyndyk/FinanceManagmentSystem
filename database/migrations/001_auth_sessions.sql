-- Migracja 001: sesje użytkowników (tokeny odświeżające) oraz indeksy tokenów e-mail
-- Uruchom na istniejącej bazie utworzonej z database/schema.sql. Skrypt jest idempotentny.

BEGIN;

CREATE TABLE IF NOT EXISTS refresh_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash varchar(64) NOT NULL UNIQUE,
    expires_at timestamptz NOT NULL,
    revoked_at timestamptz,
    created_ip varchar(45),
    user_agent varchar(255),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS refresh_tokens_user_id_idx ON refresh_tokens (user_id);

-- Wyszukiwanie po tokenach weryfikacji e-mail i resetu hasła
CREATE INDEX IF NOT EXISTS users_email_verification_token_idx ON users (email_verification_token);
CREATE INDEX IF NOT EXISTS users_password_reset_token_idx ON users (password_reset_token);

COMMIT;
